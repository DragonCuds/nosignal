#!/usr/bin/env node
// Regenerates the self-hosted emoji set from the Noto Emoji images (Apache-2.0) shipped in the
// `emoji-datasource-google` npm package. Run offline once the package is unpacked:
//   npm pack emoji-datasource-google && mkdir x && tar xzf emoji-datasource-google-*.tgz -C x
//   node scripts/gen-emoji.mjs x/package
// Writes apps/web/public/emoji/*.png (quantised with pngquant if installed), apps/web/src/emoji-files.ts
// and apps/web/src/emoji-data.ts.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const pkg = process.argv[2];
if (!pkg) { console.error('usage: node scripts/gen-emoji.mjs <emoji-datasource-google dir>'); process.exit(1); }
const root = path.resolve(import.meta.dirname, '..');
const outDir = path.join(root, 'apps/web/public/emoji');
const srcDir = path.join(pkg, 'img/google/64');
const data = JSON.parse(fs.readFileSync(path.join(pkg, 'emoji.json'), 'utf8'));

const CATEGORIES = [
  ['Smileys & Emotion', 'صورتک‌ها', '😀'], ['People & Body', 'آدم‌ها', '👋'], ['Animals & Nature', 'طبیعت', '🐻'],
  ['Food & Drink', 'خوراکی', '🍔'], ['Activities', 'فعالیت', '⚽'], ['Travel & Places', 'سفر', '🚗'],
  ['Objects', 'وسایل', '💡'], ['Symbols', 'نمادها', '❤️'], ['Flags', 'پرچم‌ها', '🏳️'],
];

fs.mkdirSync(outDir, { recursive: true });
const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.png')).sort();
const quant = spawnSync('pngquant', ['--version']).status === 0;
for (const file of files) {
  const dest = path.join(outDir, file);
  if (quant) spawnSync('pngquant', ['--quality=70-95', '--speed', '1', '--strip', '--force', '--output', dest, path.join(srcDir, file)]);
  if (!quant || !fs.existsSync(dest)) fs.copyFileSync(path.join(srcDir, file), dest);
}
const names = files.map((f) => f.slice(0, -4));
fs.writeFileSync(path.join(root, 'apps/web/src/emoji-files.ts'),
  `// Generated by scripts/gen-emoji.mjs: every emoji image available in /public/emoji (file names without .png).\nexport const emojiFiles: string[] = ${JSON.stringify(names)};\n`);

const have = new Set(names);
const toChar = (u) => String.fromCodePoint(...u.split('-').map((h) => parseInt(h, 16)));
const lines = CATEGORIES.map(([id, label, icon]) => {
  const items = data.filter((e) => e.category === id && have.has(e.image.slice(0, -4))).sort((a, b) => a.sort_order - b.sort_order).map((e) => toChar(e.unified));
  return `  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(label)}, icon: ${JSON.stringify(icon)}, items: ${JSON.stringify(items)} },`;
});
fs.writeFileSync(path.join(root, 'apps/web/src/emoji-data.ts'),
  `// Generated by scripts/gen-emoji.mjs from emoji-datasource-google (images in /public/emoji). Do not edit by hand.\nexport type EmojiCategory = { id: string; label: string; icon: string; items: string[] };\nexport const emojiCategories: EmojiCategory[] = [\n${lines.join('\n')}\n];\n`);
console.log(`images: ${names.length}, pngquant: ${quant}`);
